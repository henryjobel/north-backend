async function updateModel(Model, data, name) {
  const doc = await Model.findOne();
  if (doc) {
    await Model.updateOne({ _id: doc._id }, { $set: data });
    console.log(`Updated existing document for ${name}`);
  } else {
    await Model.create(data);
    console.log(`Created new document for ${name}`);
  }
}

